// Realistic 52-week historical freight time-series data for Australia -> East Coast India
export function generateHistoricalFreight(
  baseRate: number = 17.8,
  weeks: number = 52
): FreightHistoryPoint[] {
  const points: FreightHistoryPoint[] = [];
  const now = new Date('2026-09-12T00:00:00Z');
  
  // Seedable deterministic walk for realistic seasonality
  let currentRate = baseRate;
  let currentBdi = 1750;
  let currentBunker = 590;

  for (let i = weeks; i >= 0; i--) {
    const d = new Date(now.getTime() - i * 7 * 24 * 3600 * 1000);
    const dateStr = d.toISOString().split('T')[0];
    
    // Seasonal factor: Q3/Q4 pre-winter restocking in India & China pushes rates higher
    const weekOfYear = Math.floor((d.getTime() - new Date(d.getFullYear(), 0, 1).getTime()) / (7 * 24 * 3600 * 1000));
    const seasonalLift = Math.sin((weekOfYear / 52) * 2 * Math.PI - 1.2) * 1.8;
    
    // Mean reverting step
    const noise = Math.sin(i * 1.7) * 0.45 + Math.cos(i * 0.8) * 0.3;
    currentRate = Number((baseRate + seasonalLift + noise).toFixed(2));
    currentBdi = Math.round(1500 + (currentRate - 14) * 85 + Math.sin(i * 0.5) * 60);
    currentBunker = Number((580 + Math.sin(i * 0.4) * 45 + (currentRate * 2.1)).toFixed(1));

    points.push({
      date: dateStr,
      rateUsdPerTonne: currentRate,
      vlsfoPrice: currentBunker,
      bdi: currentBdi,
      volumeTonnes: Math.round(280000 + Math.sin(i) * 50000),
    });
  }

  return points;
}

